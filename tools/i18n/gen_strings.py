#!/usr/bin/env python3
"""Generates app/src/main/res/values-<lang>/strings.xml from tools/i18n/langs_*.txt.

Format: '@<android-qualifier>' starts a language, then 'key|text' lines.
Every key of the English strings.xml must be translated (checked); text is XML- and
Android-escaped here, so translators write plain text.
"""
import glob
import os
import re

ROOT = os.path.dirname(os.path.abspath(__file__))
RES = os.path.join(ROOT, "..", "..", "app", "src", "main", "res")


def escape(text: str) -> str:
    text = text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    return text.replace("'", "\\'").replace('"', '\\"')


english = open(os.path.join(RES, "values", "strings.xml"), encoding="utf-8").read()
keys = [k for k in re.findall(r'<string name="([^"]+)"', english) if k != "app_name"]

langs: dict[str, dict[str, str]] = {}
current = None
for path in sorted(glob.glob(os.path.join(ROOT, "langs_*.txt"))):
    for line in open(path, encoding="utf-8"):
        line = line.rstrip("\n")
        if line.startswith("@"):
            current = line[1:].strip()
            langs[current] = {}
        elif "|" in line and current:
            k, v = line.split("|", 1)
            langs[current][k.strip()] = v.strip()

for lang, table in langs.items():
    missing = [k for k in keys if k not in table]
    extra = [k for k in table if k not in keys]
    assert not missing and not extra, (lang, missing, extra)
    for k, v in table.items():
        want = sorted(re.findall(r"%\d\$s", re.search(rf'<string name="{k}">(.*?)</string>', english, re.S).group(1)))
        assert sorted(re.findall(r"%\d\$s", v)) == want, (lang, k, "placeholders differ")
    out = ['<?xml version="1.0" encoding="utf-8"?>', "<!-- Generated by tools/i18n/gen_strings.py; edit langs_*.txt instead. -->", "<resources>"]
    out += [f'    <string name="{k}">{escape(table[k])}</string>' for k in keys]
    out.append("</resources>\n")
    folder = os.path.join(RES, f"values-{lang}")
    os.makedirs(folder, exist_ok=True)
    open(os.path.join(folder, "strings.xml"), "w", encoding="utf-8").write("\n".join(out))
    print(f"values-{lang}: {len(keys)} strings")
