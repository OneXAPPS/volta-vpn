#!/usr/bin/env python3
"""Writes the monochrome 'V' glyph used as the launcher icon's themed (monochrome) layer."""
import os

RES = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "app", "src", "main", "res", "drawable")
os.makedirs(RES, exist_ok=True)

# The logo's V: a broad left stroke and a slanted right stroke meeting at the bottom.
V = "M2.5,4.5 H8 L12.2,13.8 L16.6,3.5 H21.5 L14,19.5 H10.4 Z"


def vector(body: str, size: int = 24) -> str:
    return (f'<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
            f'    android:width="{size}dp" android:height="{size}dp"\n'
            f'    android:viewportWidth="24" android:viewportHeight="24">\n{body}</vector>\n')


def write(name: str, text: str) -> None:
    with open(os.path.join(RES, name), "w", encoding="utf-8") as fh:
        fh.write("<?xml version=\"1.0\" encoding=\"utf-8\"?>\n<!-- Generated by tools/brand/make_glyphs.py -->\n" + text)


filled = f'    <path android:fillColor="#FFFFFFFF" android:pathData="{V}" />\n'
outline = (f'    <path android:strokeColor="#FFFFFFFF" android:strokeWidth="1.6" android:strokeLineJoin="round"\n'
           f'        android:fillColor="#00000000" android:pathData="{V}" />\n')

write("ic_glyph_v.xml", vector(filled))                 # themed (monochrome) launcher icon
print("glyphs written")
